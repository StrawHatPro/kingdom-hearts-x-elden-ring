use std::sync::OnceLock;

use super::alter::FIRST_CHARACTER_TALK;
use super::rules::{cmd, env, Decision, Val};

/// OpenEnhanceShop(kind): the reinforcement menu (the sheet's `smith.forge.open_enhance`; this is its fallback).
pub const OPEN_ENHANCE: i32 = 24;

/// THE SHEET'S SMITH ROWS (sora-er-shop `smith.forge`, `smith.trim`, `smith.talk_ids`).
#[derive(Clone, Debug, PartialEq)]
pub struct SmithRules {
    pub open_enhance: i32,
    /// Query 59's menu types of the reinforcement menu (what the scripts wait on right after 24).
    pub menu_types: Vec<i32>,
    /// Commands not run in a smith's script (the safety net).
    pub swallow: Vec<i32>,
    /// EventTextForTalk ids of the talk-list options a smith's script does not add.
    pub trim: Vec<i32>,
    /// The scripts that run 24 (the scan of the game's scripts).
    pub talk_ids: Vec<i32>,
    /// Rows that were missing or not understood.
    pub problems: Vec<String>,
}

impl Default for SmithRules {
    fn default() -> SmithRules {
        SmithRules { open_enhance: OPEN_ENHANCE, menu_types: Vec::new(), swallow: Vec::new(), trim: Vec::new(), talk_ids: Vec::new(), problems: Vec::new() }
    }
}

impl SmithRules {
    pub fn parse(text: &str) -> SmithRules {
        let mut out = SmithRules::default();
        let Ok(json) = serde_json::from_str::<serde_json::Value>(text) else {
            out.problems.push("the sheet is not JSON".to_string());
            return out;
        };
        let ints = |v: &serde_json::Value| v.as_array().map(|a| a.iter().filter_map(|x| x.as_i64().and_then(|n| i32::try_from(n).ok())).collect::<Vec<_>>()).unwrap_or_default();
        let (mut forge, mut trim) = (false, false);
        for row in json["rows"].as_array().map(Vec::as_slice).unwrap_or(&[]) {
            let (Some(id), value) = (row[0].as_str(), &row[1]) else { continue };
            match id {
                "smith.forge" => {
                    forge = true;
                    out.open_enhance = value["open_enhance"].as_i64().and_then(|n| i32::try_from(n).ok()).unwrap_or(OPEN_ENHANCE);
                    out.menu_types = ints(&value["menu_types"]);
                    out.swallow = ints(&value["swallow"]);
                }
                "smith.trim" => {
                    trim = true;
                    out.trim = ints(value);
                }
                "smith.talk_ids" => out.talk_ids = ints(value),
                _ => {}
            }
        }
        for (have, row) in [(forge, "smith.forge"), (trim, "smith.trim")] {
            if !have {
                out.problems.push(format!("no row {row}"));
            }
        }
        out
    }

    /// The sheet on disk (kh-host's `SHEET_PATH`, the tree the binary was built from) when it reads, else the compiled copy.
    pub fn load() -> SmithRules {
        if let Ok(text) = std::fs::read_to_string(kh_host::shop::SHEET_PATH) {
            let rules = SmithRules::parse(&text);
            if rules.problems.is_empty() {
                return rules;
            }
        }
        SmithRules::parse(kh_host::shop::SHEET)
    }
}

/// The rules of this process (read once).
pub fn rules() -> &'static SmithRules {
    static RULES: OnceLock<SmithRules> = OnceLock::new();
    RULES.get_or_init(SmithRules::load)
}

/// A smith's request for the Keyblade Forge (his reinforcement menu, swallowed).
#[derive(Clone, Debug, PartialEq)]
pub struct ForgeRequest {
    pub talk_id: i32,
    /// The talk object (its character: the smith's name).
    pub ins: usize,
    /// OpenEnhanceShop's argument (0 a smith, 1 the Smithing Table; for the log).
    pub kind: i32,
    pub serial: u32,
    /// forgekh.rs opened the Forge for it.
    pub opened: bool,
}

#[derive(Clone, Debug, Default)]
pub struct SmithTalk {
    /// `forge.kh` on (default; forgekh.rs sets it each frame).
    pub on: bool,
    pub rules: SmithRules,
    /// Scripts seen running 24 that the sheet does not list.
    pub seen: Vec<i32>,
    /// The request waiting for / shown by the Forge (at most one).
    pub request: Option<ForgeRequest>,
    serial: u32,
    /// (talk, menu type) of a query 59 told once (a type the sheet does not list, asked while the Forge stands in).
    told: Vec<(i32, i32)>,
    /// Log lines for the frame (`forge:` lines).
    pub notes: Vec<String>,
}

impl SmithTalk {
    /// A smith's script: the sheet's, or one seen running the reinforcement command.
    pub fn is_smith(&self, talk_id: i32) -> bool {
        self.rules.talk_ids.contains(&talk_id) || self.seen.contains(&talk_id)
    }

    /// A COMMAND of a talk script: `Some(Swallow)` = the game does not run it (the Forge stands in, or it is trimmed).
    pub fn on_event(&mut self, talk_id: i32, ins: usize, id: i32, args: &[Val]) -> Option<Decision> {
        if !self.on || talk_id < FIRST_CHARACTER_TALK {
            return None;
        }
        let int = |k: usize| args.get(k).and_then(Val::int);
        if id == self.rules.open_enhance {
            if !self.is_smith(talk_id) {
                self.seen.push(talk_id);
                self.notes.push(format!("talk {talk_id}: runs the reinforcement menu and is not in smith.talk_ids: a smith from now on (its options trimmed too)"));
            }
            if let Some(old) = self.request.as_ref().filter(|r| r.talk_id != talk_id) {
                self.notes.push(format!("talk {}: its Forge request is replaced by talk {talk_id}'s", old.talk_id));
            }
            self.serial = self.serial.wrapping_add(1);
            let kind = int(0).unwrap_or(-1);
            self.notes.push(format!("talk {talk_id}: Elden Ring's reinforcement menu (command {id}({kind})) -> KH3's Keyblade Forge"));
            self.request = Some(ForgeRequest { talk_id, ins, kind, serial: self.serial, opened: false });
            return Some(Decision::Swallow);
        }
        if !self.is_smith(talk_id) {
            return None;
        }
        if id == cmd::ADD_LIST || id == cmd::ADD_LIST_ALT {
            // (a 19 with four arguments: the conditional form with its condition still first)
            let texts = [int(1), if id == cmd::ADD_LIST && args.len() == 4 { int(2) } else { None }];
            if let Some(msg) = texts.into_iter().flatten().find(|m| self.rules.trim.contains(m)) {
                self.notes.push(format!("talk {talk_id}: option {} (text {msg}) not added: a smith's option that is not an upgrade (smith.trim)", int(0).unwrap_or(-1)));
                return Some(Decision::Swallow);
            }
            return None;
        }
        if self.rules.swallow.contains(&id) {
            self.notes.push(format!("talk {talk_id}: command {id} is not run in a smith's talk (smith.forge.swallow: its options are trimmed)"));
            return Some(Decision::Swallow);
        }
        None
    }

    /// A QUERY AFTER THE GAME ANSWERED IT: `Some(1)` = the reinforcement menu reads open while the Forge stands in for it
    /// (that talk only; its menu types or "any").
    pub fn on_env(&mut self, talk_id: i32, id: i32, args: &[Val]) -> Option<i32> {
        if id != env::MENU_OPEN {
            return None;
        }
        self.request.as_ref().filter(|r| r.talk_id == talk_id)?;
        let wanted = args.first().and_then(Val::int).unwrap_or(-1);
        if wanted == -1 || self.rules.menu_types.is_empty() || self.rules.menu_types.contains(&wanted) {
            return Some(1);
        }
        if !self.told.contains(&(talk_id, wanted)) {
            self.told.push((talk_id, wanted));
            self.notes.push(format!("talk {talk_id}: asks whether menu type {wanted} is open while the Forge stands in (not one of smith.forge menu_types {:?}): the game's answer", self.rules.menu_types));
        }
        None
    }

    /// The Forge closed (or could not open): the script reads the game's own "closed" from now on.
    pub fn done(&mut self, why: &str) -> Option<ForgeRequest> {
        let r = self.request.take()?;
        self.notes.push(format!("talk {}: the Keyblade Forge is done ({why}): the smith's talk list comes back", r.talk_id));
        Some(r)
    }
}

