/// The two latest regions in draw order (pure, tested): a region drawn again moves to the end.
fn push_region(list: [Stamped; 2], tables: LitTables, now: std::time::Instant) -> [Stamped; 2] {
    if list[1].is_some_and(|(t, _)| t == tables) {
        return [list[0], Some((tables, now))];
    }
    if list[0].is_some_and(|(t, _)| t == tables) {
        return [list[1], Some((tables, now))];
    }
    [list[1], Some((tables, now))]
}

/// This frame's light inputs (each seen within `FOG_FRESH`).
pub(crate) fn lit_binds() -> LitBinds {
    let fresh = |s: Stamped| s.filter(|(_, at)| at.elapsed() < FOG_FRESH).map(|(t, _)| t);
    let tile = TILE_BIND.lock().ok().and_then(|g| fresh(*g));
    let pass = PASS_BIND.lock().ok().and_then(|g| fresh(*g));
    let regions = REGION_BINDS.lock().ok().map(|g| [fresh(g[0]), fresh(g[1])]).unwrap_or([None, None]);
    LitBinds { tile, pass, regions: close_gap(regions) }
}

/// The regions without a gap (the older one first).
fn close_gap(regions: [Option<LitTables>; 2]) -> [Option<LitTables>; 2] {
    match regions {
        [None, Some(b)] => [Some(b), None],
        r => r,
    }
}

/// For the log: the light inputs' draws seen since the last call and what is this frame's.
fn lit_status() -> String {
    let b = lit_binds();
    let seen = LIT_SEEN.each_ref().map(|a| a.swap(0, Ordering::Relaxed));
    format!(
        "(PARTY-NATIVE-LIGHT) the game's light inputs: tile lighting {} draw(s) this second ({}), particle pass {} hand-over(s) ({}), irradiance regions {} ({} this frame)",
        seen[0],
        if b.tile.is_some() { "this frame's" } else { "none fresh" },
        seen[1],
        if b.pass.is_some() { "this frame's" } else { "none fresh" },
        seen[2],
        b.regions.iter().filter(|r| r.is_some()).count()
    ) + "; " + &discover_status()
}

/// The roles of a pipeline state of the game, as text for cbcap.rs's dump ("" = none recognised).
pub(crate) fn role_text(pso: usize) -> String {
    ROLES.lock().ok().and_then(|g| g.as_ref().and_then(|m| m.get(&pso)).map(|r| r.iter().map(|x| x.name()).collect::<Vec<_>>().join("+"))).unwrap_or_default()
}

/// For the log: how many of the game's pipeline states are recognised, by role.
pub(crate) fn status() -> String {
    let counts = ROLES.lock().ok().and_then(|g| {
        g.as_ref().map(|m| {
            let mut c: HashMap<&'static str, u32> = HashMap::new();
            for r in m.values().flatten() {
                *c.entry(r.name()).or_default() += 1;
            }
            let mut v: Vec<String> = c.into_iter().map(|(k, n)| format!("{k} {n}")).collect();
            v.sort();
            v.join(", ")
        })
    });
    let fog = match fog_last() {
        Some(f) => format!("the fog composite drawn {} time(s) this second (heaps {:#x} {:#x}, b0..b3 table {:#x}, t0..t3 table {:#x})", FOG_DRAWS.swap(0, Ordering::Relaxed), f.heaps[0], f.heaps[1], f.buffers, f.textures),
        None => "the fog composite not seen yet".to_string(),
    };
    format!("(PARTY-NATIVE) the game's lit / fogged effect pipelines recognised: {}; {fog}; {}", counts.filter(|s| !s.is_empty()).unwrap_or_else(|| "none yet".to_string()), lit_status())
}

