//! (PARTY-NATIVE) ELDEN RING'S OWN LIT / FOGGED TRANSLUCENT EFFECTS, RECOGNISED (the user 2026-11-05: "literally the lighting code
//! needs to work for ALL KH objects"; the coordinator: light and fog the KH translucent effects exactly as Elden Ring does its own).
//!
//! Elden Ring lights its lit particles per particle (the geometry / domain shader: two irradiance volumes + the tile-clustered
//! local lights into three L1 SH vectors) and per pixel (the sun x its froxel shadow volume), and fogs 252 of its 279 particle
//! pixel shaders with the volumetric fog's 3D in-scatter / transmittance volume (offline research:
//! build/sora_tmp/weapons/PARTY-NATIVE/ffx/FFX_FINDINGS.md, from gxffxshader.shaderbnd of 2.7.2.0 and gxrenderershader's
//! GXVolumetricFog_SceneComposite). Those inputs are D3D12 bindings of the game's one "GX" root signature, so they are found in
//! the command stream, not by an address of the exe: the pipeline states made from these shaders are recognised here by the
//! DIGEST OF THEIR DXIL `HASH` PART when the game makes them (shaft.rs's creation hooks call `note`), and cbcap.rs's discovery
//! dump names their draws and tables (`r.cbcap`). The shaders are version-stable (PORT: identical in 2.7.2.0).
//!
//! Nothing here draws or changes a frame: it only recognises and counts.

use std::collections::HashMap;
use std::sync::atomic::{AtomicU32, AtomicUsize, Ordering};
use std::sync::Mutex;

/// What a recognised pipeline state of the game is.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub(crate) enum Role {
    /// A particle pixel shader lit per pixel by the sun + the per-particle SH (`PS_VFX_*AllLight*` / `*BumpLight*`).
    LitPs,
    /// The sun alone (`PS_VFX_*DirLight*`).
    DirLitPs,
    /// The geometry shader that works out the per-particle SH (`GS_VFX_StandardParticle{BumpLight,DirLight}*`).
    LitGs,
    /// The tessellated sprites' domain shader that does the same per vertex (`GXFfx*Bump*.dpo`).
    LitDs,
    /// Any other particle pixel shader that applies the volumetric fog (`g_volumetricFog`).
    FoggedPs,
    /// The world's fog composite (`GXVolumetricFog_SceneComposite`, one full-screen draw a frame) and its two halves.
    FogComposite,
    FogInScatter,
    FogTransmittance,
    /// (PARTY-NATIVE-LIGHT) the deferred tile-clustered local lights (`GXRend_TileBasedLighting(Sdw)`, every frame): its tables hold
    /// cbSceneParam (b8), cbLightAccParam (b0) and the light buffers t59..t62
    TileLighting,
    /// (PARTY-NATIVE-LIGHT) a deferred irradiance-volume region (`GXEnvMapRegion[Box][Diff*]` without [Lerp]): CB_ENVMAP_REGION (b3)
    /// and its volume t27..t30
    EnvRegion,
    /// (PARTY-NATIVE-LIGHT round 2) `GS_VFX_SparkParticle(Correct)`: the same gcbSceneParam (b10) and volumes (t8..t15) as the lit
    /// particles' geometry shader: a particle pass source
    SparkGs,
    /// (PARTY-NATIVE-LIGHT round 2, discovery) the irradiance-volume builders (`GXGiVolume_*.cpo`, `GXEnvMapRegion_Copy3DTo3D*`), their
    /// pixel passes (`GXGiVolume_*.ppo`), the other region shaders ([Lerp], [Spc*], [Stencil], debug) and the GPU billboards
    /// (`GS_GpuBillboard` reads the volumes W, `CS_GpuBillboard*`): where the game binds its volumes in ordinary frames
    GiCompute,
    GiPixel,
    RegionOther,
    BillboardIv,
    /// (PARTY-NATIVE-LIGHT round 3) a deferred region that blends TWO volumes (`GXEnvMapRegion[Box][Diff*][Lerp|LerpDiff]`: t27..t30
    /// and t31..t34, lerp by CB_ENVMAP_REGION row 26.x, the second's safe voxel row 33): a region source
    EnvRegionLerp,
}

impl Role {
    pub(crate) fn name(self) -> &'static str {
        match self {
            Role::LitPs => "ffx-lit-ps",
            Role::DirLitPs => "ffx-dirlit-ps",
            Role::LitGs => "ffx-lit-gs",
            Role::LitDs => "ffx-lit-ds",
            Role::FoggedPs => "ffx-fogged-ps",
            Role::FogComposite => "fog-composite",
            Role::FogInScatter => "fog-inscatter",
            Role::FogTransmittance => "fog-transmittance",
            Role::TileLighting => "tile-lighting",
            Role::EnvRegion => "env-region",
            Role::SparkGs => "ffx-spark-gs",
            Role::GiCompute => "gi-cs",
            Role::GiPixel => "gi-ps",
            Role::RegionOther => "env-region-other",
            Role::BillboardIv => "billboard-iv",
            Role::EnvRegionLerp => "env-region-lerp",
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Stage {
    Pixel,
    Geometry,
    Domain,
    /// (PARTY-NATIVE-LIGHT round 2) a compute pipeline's shader
    Compute,
}

/// The role of a shader by its DXIL `HASH` digest (pure, tested). A lit pixel shader is also fogged: it is named lit.
pub(crate) fn role_of_hash(hash: &[u8; 16], stage: Stage) -> Option<Role> {
    let has = |table: &[[u8; 16]]| table.contains(hash);
    match stage {
        Stage::Pixel if has(LIT_PS) => Some(Role::LitPs),
        Stage::Pixel if has(DIRLIT_PS) => Some(Role::DirLitPs),
        Stage::Pixel if has(FOG_COMPOSITE) => Some(Role::FogComposite),
        Stage::Pixel if has(FOG_INSCATTER) => Some(Role::FogInScatter),
        Stage::Pixel if has(FOG_TRANSMITTANCE) => Some(Role::FogTransmittance),
        Stage::Pixel if has(TILE_PS) => Some(Role::TileLighting), // (PARTY-NATIVE-LIGHT)
        Stage::Pixel if has(REGION_PS) => Some(Role::EnvRegion),
        Stage::Pixel if has(FOGGED_PS) => Some(Role::FoggedPs),
        Stage::Geometry if has(LIT_GS) => Some(Role::LitGs),
        Stage::Domain if has(LIT_DS) => Some(Role::LitDs),
        // (PARTY-NATIVE-LIGHT round 2)
        Stage::Pixel if has(GI_PS) => Some(Role::GiPixel),
        Stage::Pixel if has(REGION_LERP_PS) => Some(Role::EnvRegionLerp), // (round 3: before the other regions)
        Stage::Pixel if has(REGION_OTHER_PS) => Some(Role::RegionOther),
        Stage::Geometry if has(SPARK_GS) => Some(Role::SparkGs),
        Stage::Geometry | Stage::Compute if has(BILLBOARD_IV) => Some(Role::BillboardIv),
        Stage::Compute if has(GI_CS) => Some(Role::GiCompute),
        _ => None,
    }
}

/// The recognised pipeline states: the object's address -> its roles (a lit particle has a lit PS and a lit GS).
static ROLES: Mutex<Option<HashMap<usize, Vec<Role>>>> = Mutex::new(None);
static SEEN: AtomicU32 = AtomicU32::new(0);

/// shaft.rs's creation hooks: the game made the pipeline state `made` with these shaders' bytecode.
pub(crate) fn note(made: usize, ps: &[u8], gs: &[u8], ds: &[u8]) {
    let mut roles = Vec::new();
    for (code, stage) in [(ps, Stage::Pixel), (gs, Stage::Geometry), (ds, Stage::Domain)] {
        if let Some(role) = crate::shaft::dxil_hashes(code).and_then(|(h, _)| role_of_hash(&h, stage)) {
            roles.push(role);
        }
    }
    note_roles(made, roles);
}

/// (PARTY-NATIVE-LIGHT round 2) shaft.rs's creation hooks: the game made the compute pipeline state `made` with this shader.
pub(crate) fn note_compute(made: usize, cs: &[u8]) {
    let roles: Vec<Role> = crate::shaft::dxil_hashes(cs).and_then(|(h, _)| role_of_hash(&h, Stage::Compute)).into_iter().collect();
    note_roles(made, roles);
}

fn note_roles(made: usize, roles: Vec<Role>) {
    if roles.is_empty() || made == 0 {
        return;
    }
    let n = SEEN.fetch_add(1, Ordering::Relaxed) + 1;
    if n == 1 || n.is_power_of_two() {
        crate::rlog!("render: (PARTY-NATIVE) the game's lit / fogged effect pipelines recognised by their DXIL hash: {n} so far (latest {made:#x}: {})", roles.iter().map(|r| r.name()).collect::<Vec<_>>().join(" + "));
    }
    // (lock-free for the draw hook: the composite's pipeline states, a handful)
    if roles.contains(&Role::FogComposite) && !is_fog_composite(made) {
        for slot in &COMPOSITES {
            if slot.compare_exchange(0, made, Ordering::Relaxed, Ordering::Relaxed).is_ok() {
                break;
            }
        }
    }
    // (PARTY-NATIVE-LIGHT) the light passes and every particle pipeline, in lock-free sets for the draw hook
    for role in &roles {
        match role {
            Role::TileLighting => set_insert(&TILES, made),
            Role::EnvRegion => set_insert(&REGIONS, made),
            Role::LitPs | Role::DirLitPs | Role::LitGs | Role::FoggedPs | Role::SparkGs => set_insert(&PARTICLES, made),
            // (round 3) the tessellated lit particles: their domain stage's DSCommonBuffer + volumes are a pass source of their own
            Role::LitDs => {
                set_insert(&PARTICLES, made);
                set_insert(&DS_PARTICLES, made);
            }
            Role::EnvRegionLerp => set_insert(&REGIONS_LERP, made),
            Role::GiCompute | Role::GiPixel | Role::RegionOther | Role::BillboardIv => set_insert(&DISCOVER, made),
            Role::FogComposite | Role::FogInScatter | Role::FogTransmittance => {}
        }
    }
    if let Ok(mut g) = ROLES.lock() {
        g.get_or_insert_with(HashMap::new).insert(made, roles);
    }
}

/// The fog composite's pipeline states (`note`), for the draw hook's check without a lock.
static COMPOSITES: [AtomicUsize; 8] = [const { AtomicUsize::new(0) }; 8];

/// cbcap.rs's draw hook, at a full-screen draw: the pipeline state is the game's fog composite.
#[inline]
pub(crate) fn is_fog_composite(pso: usize) -> bool {
    pso != 0 && COMPOSITES.iter().any(|s| s.load(Ordering::Relaxed) == pso)
}

/// (PARTY-NATIVE) WHAT THE GAME'S FOG COMPOSITE BOUND at its full-screen draw this frame: the views / samplers heaps and its
/// pixel-stage tables of the GX root signature, param 28 (b0..b3: CB_SHADER_COMMON_PARAM at b0) and param 30 (t0..t3:
/// g_InScatterTex at t0). The fog of the KH translucent effects reads the same buffer and volume (FFX_FINDINGS.md section 5).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub(crate) struct FogBind {
    pub heaps: [usize; 2],
    pub buffers: u64,
    pub textures: u64,
}

static FOG_BIND: Mutex<Option<(FogBind, std::time::Instant)>> = Mutex::new(None);
static FOG_DRAWS: AtomicU32 = AtomicU32::new(0);
/// A composite's bindings are THIS frame's when it was drawn this recently (the game's descriptor ring moves on per frame).
const FOG_FRESH: std::time::Duration = std::time::Duration::from_millis(40);

/// cbcap.rs's draw hook: the fog composite was drawn with these bindings.
pub(crate) fn fog_seen(bind: FogBind) {
    if bind.heaps[0] == 0 || bind.buffers == 0 || bind.textures == 0 {
        return;
    }
    FOG_DRAWS.fetch_add(1, Ordering::Relaxed);
    if let Ok(mut f) = FOG_BIND.lock() {
        *f = Some((bind, std::time::Instant::now()));
    }
}

/// This frame's fog composite's bindings (None: not seen in the last `FOG_FRESH`).
pub(crate) fn fog_bind() -> Option<FogBind> {
    FOG_BIND.lock().ok().and_then(|f| *f).filter(|(_, at)| at.elapsed() < FOG_FRESH).map(|(b, _)| b)
}

/// The latest bindings whatever their age (for the status line).
fn fog_last() -> Option<FogBind> {
    FOG_BIND.lock().ok().and_then(|f| *f).map(|(b, _)| b)
}

