    /// A DXBC container with one `HASH` part carrying `digest` (the layout shaft.rs dxil_hashes reads).
    fn container(digest: [u8; 16]) -> Vec<u8> {
        let mut b = vec![0u8; 36];
        b[0..4].copy_from_slice(b"DXBC");
        b[28..32].copy_from_slice(&1u32.to_le_bytes());
        b[32..36].copy_from_slice(&36u32.to_le_bytes());
        b.extend_from_slice(b"HASH");
        b.extend_from_slice(&20u32.to_le_bytes());
        b.extend_from_slice(&[0u8; 4]);
        b.extend_from_slice(&digest);
        let total = b.len() as u32;
        b[24..28].copy_from_slice(&total.to_le_bytes());
        b
    }

    /// (PARTY-NATIVE) the game's lit particle, its geometry stage and the fog composite are told apart by their digests
    #[test]
    fn party_native_the_games_lit_and_fogged_effect_shaders_are_recognised() {
        assert_eq!(role_of_hash(&LIT_PS[0], Stage::Pixel), Some(Role::LitPs));
        assert_eq!(role_of_hash(&LIT_GS[0], Stage::Geometry), Some(Role::LitGs));
        assert_eq!(role_of_hash(&LIT_GS[0], Stage::Pixel), None, "a stage's digest only counts in its stage");
        assert_eq!(role_of_hash(&FOG_COMPOSITE[0], Stage::Pixel), Some(Role::FogComposite));
        assert_eq!(role_of_hash(&[0u8; 16], Stage::Pixel), None);
        assert_eq!((LIT_PS.len(), DIRLIT_PS.len(), LIT_GS.len(), LIT_DS.len(), FOGGED_PS.len()), (16, 16, 4, 14, 170));
        let code = container(FOG_COMPOSITE[0]);
        let (h, _) = crate::shaft::dxil_hashes(&code).expect("a HASH part");
        assert_eq!(h, FOG_COMPOSITE[0]);
        note(0x1234, &code, &[], &[]);
        assert_eq!(role_text(0x1234), "fog-composite");
        assert_eq!(role_text(0x9999), "");
    }

    /// (PARTY-NATIVE-LIGHT) the light passes are recognised by their digests, kept in the lock-free sets, and a draw hands over
    /// exactly the tables its source binds (none when one it needs is missing); the two latest regions stay in draw order
    #[test]
    fn party_native_light_the_games_light_inputs_are_recognised_and_kept() {
        assert_eq!(role_of_hash(&TILE_PS[0], Stage::Pixel), Some(Role::TileLighting));
        assert_eq!(role_of_hash(&TILE_PS[1], Stage::Pixel), Some(Role::TileLighting));
        assert_eq!(role_of_hash(&REGION_PS[0], Stage::Pixel), Some(Role::EnvRegion));
        assert_eq!(role_of_hash(&TILE_PS[0], Stage::Geometry), None);
        assert_eq!((TILE_PS.len(), REGION_PS.len()), (2, 8));
        note(0x5_0000, &container(TILE_PS[1]), &[], &[]);
        note(0x6_0000, &container(REGION_PS[3]), &[], &[]);
        note(0x7_0000, &container(LIT_PS[0]), &container(LIT_GS[0]), &[]);
        assert_eq!((lit_kind(0x5_0000), lit_kind(0x6_0000), lit_kind(0x7_0000), lit_kind(0x8_0000), lit_kind(0)), (Some(LitKind::Tile), Some(LitKind::Region), Some(LitKind::Particle), None, None));
        // a set takes each address once and finds every one of a crowd
        let set: [AtomicUsize; 8] = [const { AtomicUsize::new(0) }; 8];
        for v in [0x10, 0x20, 0x10, 0x30] {
            set_insert(&set, v);
        }
        assert_eq!(set.iter().filter(|s| s.load(Ordering::Relaxed) != 0).count(), 3);
        assert!(set_has(&set, 0x20) && !set_has(&set, 0x40) && !set_has(&set, 0));
        // the tables: PS 28, PS 29, PS 32, GS 22, GS 24
        let t = [1, 2, 3, 4, 5, 6, 7];
        assert_eq!(LIT_PARAMS, [28, 29, 32, 22, 24, 14, 17]);
        assert_eq!(lit_tables(LitKind::Tile, [9, 0], t), Some(LitTables { heaps: [9, 0], low_cbv: 1, high_cbv: 2, high_srv: 3, ..Default::default() }));
        assert_eq!(lit_tables(LitKind::Region, [9, 0], t), Some(LitTables { heaps: [9, 0], low_cbv: 1, high_srv: 3, ..Default::default() }));
        assert_eq!(lit_tables(LitKind::Particle, [9, 0], t), Some(LitTables { heaps: [9, 0], high_cbv: 4, mid_srv: 5, ..Default::default() }));
        assert_eq!(lit_tables(LitKind::Particle, [9, 0], [1, 2, 3, 4, 0, 6, 7]), None, "no volumes table");
        // (round 3) the tessellated lit particles: DS 14 (DSCommonBuffer) / DS 17 (the volumes); the two-volume regions
        assert_eq!(lit_tables(LitKind::DsParticle, [9, 0], t), Some(LitTables { heaps: [9, 0], low_cbv: 6, mid_srv: 7, variant: 1, ..Default::default() }));
        assert_eq!(lit_tables(LitKind::DsParticle, [9, 0], [1, 2, 3, 4, 5, 6, 0]), None);
        assert_eq!(lit_tables(LitKind::RegionLerp, [9, 0], t), Some(LitTables { heaps: [9, 0], low_cbv: 1, high_srv: 3, variant: 1, ..Default::default() }));
        assert_eq!(lit_tables(LitKind::Tile, [0, 0], t), None, "no heap");
        let now = std::time::Instant::now();
        let (a, b, c) = (LitTables { low_cbv: 1, ..Default::default() }, LitTables { low_cbv: 2, ..Default::default() }, LitTables { low_cbv: 3, ..Default::default() });
        let r = push_region([None, None], a, now);
        let r = push_region(r, b, now);
        assert_eq!(r.map(|x| x.map(|y| y.0)), [Some(a), Some(b)]);
        assert_eq!(push_region(r, a, now).map(|x| x.map(|y| y.0)), [Some(b), Some(a)], "drawn again: the latest");
        assert_eq!(push_region(r, c, now).map(|x| x.map(|y| y.0)), [Some(b), Some(c)]);
        assert_eq!(close_gap([None, Some(a)]), [Some(a), None]);
    }

    /// (PARTY-NATIVE-LIGHT round 2) the spark particles' geometry shader is a pass source; the volume builders (compute), their pixel
    /// passes, the other region shaders and the GPU billboards are discovery roles, also when made as compute pipelines
    #[test]
    fn party_native_light_round2_the_volume_passes_are_recognised() {
        assert_eq!(role_of_hash(&SPARK_GS[0], Stage::Geometry), Some(Role::SparkGs));
        assert_eq!(role_of_hash(&GI_CS[0], Stage::Compute), Some(Role::GiCompute));
        assert_eq!(role_of_hash(&GI_CS[0], Stage::Pixel), None, "a compute digest counts in the compute stage only");
        assert_eq!(role_of_hash(&GI_PS[0], Stage::Pixel), Some(Role::GiPixel));
        // (round 3: the [Lerp] ones among them are region sources now)
        let other = *REGION_OTHER_PS.iter().find(|h| !REGION_LERP_PS.contains(h)).expect("a non-lerp region shader");
        assert_eq!(role_of_hash(&other, Stage::Pixel), Some(Role::RegionOther));
        assert!(REGION_LERP_PS.iter().all(|h| REGION_OTHER_PS.contains(h) && role_of_hash(h, Stage::Pixel) == Some(Role::EnvRegionLerp)));
        assert!(REGION_OTHER_PS.iter().all(|h| !REGION_PS.contains(h)), "the regions taken are not discovery ones");
        assert_eq!((GI_CS.len(), GI_PS.len(), REGION_OTHER_PS.len(), SPARK_GS.len(), BILLBOARD_IV.len()), (31, 26, 13, 2, 5));
        note_compute(0x9_0000, &container(GI_CS[3]));
        note(0xa_0000, &container(FOGGED_PS[0]), &container(SPARK_GS[1]), &[]);
        note(0xb_0000, &container(other), &[], &[]);
        assert_eq!((lit_kind(0x9_0000), lit_kind(0xa_0000), lit_kind(0xb_0000)), (Some(LitKind::Discover), Some(LitKind::Particle), Some(LitKind::Discover)));
        assert!(is_discover(0x9_0000) && !is_discover(0xa_0000));
        assert_eq!(role_text(0x9_0000), "gi-cs");
        assert_eq!(discovery_names(&[Role::FoggedPs, Role::GiPixel, Role::BillboardIv]), ["gi-ps", "billboard-iv"]);
        assert_eq!(lit_tables(LitKind::Discover, [1, 0], [1; LIT_N]), None, "a discovery draw hands nothing over");
        // (round 3) a tessellated lit particle and a two-volume region are told apart
        note(0xc_0000, &container(FOGGED_PS[0]), &[], &container(LIT_DS[2]));
        note(0xd_0000, &container(REGION_LERP_PS[4]), &[], &[]);
        assert_eq!((lit_kind(0xc_0000), lit_kind(0xd_0000)), (Some(LitKind::DsParticle), Some(LitKind::RegionLerp)));
        assert_eq!(role_of_hash(&REGION_LERP_PS[0], Stage::Pixel), Some(Role::EnvRegionLerp));
        discover_dispatch(0x9_0000, [1, 2], [3; 8]);
        assert!(discover_status().contains("gi-cs 1 (heaps 0x1 0x2"));
    }
