//! Points `src/lib.rs` at the generated constants: `node tools/gen_port.js` writes
//! `build/gen/rust/sora_camera_params.rs` from `sheets/port/sora-camera.json`. Set
//! `KH_GEN_RUST_DIR` to build against another folder.

use std::env;
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-env-changed=KH_GEN_RUST_DIR");
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let dir = match env::var("KH_GEN_RUST_DIR") {
        Ok(p) if !p.is_empty() => PathBuf::from(p),
        _ => manifest.join("..").join("..").join("build").join("gen").join("rust"),
    };
    let path = dir.join("sora_camera_params.rs");
    println!("cargo:rerun-if-changed={}", path.display());
    if !path.is_file() {
        panic!("\n\nkh-camera: generated file not found: {}\n  run:  node tools/gen_port.js   (or build.ps1)\n\n", path.display());
    }
    println!("cargo:rustc-env=KH_SORA_CAMERA_PARAMS_RS={}", path.display());
    // (NF) KH3's near-camera / see-through fade of the characters (src/camfade.rs): sheets/port/sora-camera-fade.json and
    // sora-camera-fade-volumes.json, generated by node tools/gen_port.js
    for (file, var) in [("sora_camera_fade.rs", "KH_SORA_CAMERA_FADE_RS"), ("sora_camera_fade_volumes.rs", "KH_SORA_CAMERA_FADE_VOLUMES_RS")] {
        let p = dir.join(file);
        println!("cargo:rerun-if-changed={}", p.display());
        if !p.is_file() {
            panic!("\n\nkh-camera: generated file not found: {}\n  run:  node tools/gen_port.js   (or build.ps1)\n\n", p.display());
        }
        println!("cargo:rustc-env={var}={}", p.display());
    }
    // (party stream D) the team-attack CameraAnims, written by `node tools/party_team_pack.js`;
    // without the file camera_anim.rs builds with empty tables (cfg kh_party_team_cameras off).
    println!("cargo::rustc-check-cfg=cfg(kh_party_team_cameras)");
    let team = dir.join("party_team_cameras.rs");
    println!("cargo:rerun-if-changed={}", team.display());
    if team.is_file() {
        println!("cargo:rustc-cfg=kh_party_team_cameras");
        println!("cargo:rustc-env=KH_PARTY_TEAM_CAMERAS_RS={}", team.display());
    }
}
