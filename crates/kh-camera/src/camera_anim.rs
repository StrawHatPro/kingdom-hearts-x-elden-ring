/// Hermite (`FMath::CubicInterp`).
fn cubic(p0: f32, t0: f32, p1: f32, t1: f32, a: f32) -> f32 {
    let (a2, a3) = (a * a, a * a * a);
    (2.0 * a3 - 3.0 * a2 + 1.0) * p0 + (a3 - 2.0 * a2 + a) * t0 + (a3 - a2) * t1 + (-2.0 * a3 + 3.0 * a2) * p1
}

/// `FInterpCurve<float>::Eval` (UE 4.17 [U]): before the first key its value, after the last key
/// its value; between keys by the PREVIOUS key's mode: constant, linear, or cubic Hermite with the
/// stored tangents scaled by the key interval.
pub fn eval_curve(keys: &[CurveKeyDef<f32>], t: f32, default: f32) -> f32 {
    let n = keys.len();
    if n == 0 {
        return default;
    }
    if n < 2 || t < keys[0].t {
        return keys[0].v;
    }
    if t >= keys[n - 1].t {
        return keys[n - 1].v;
    }
    let i = keys.iter().rposition(|k| k.t <= t).unwrap_or(0);
    let (p, q) = (&keys[i], &keys[i + 1]);
    let diff = q.t - p.t;
    if diff > 0.0 && p.m != CurveMode::Constant {
        let alpha = (t - p.t) / diff;
        if p.m == CurveMode::Linear {
            p.v + (q.v - p.v) * alpha
        } else {
            cubic(p.v, p.l * diff, q.v, q.a * diff, alpha)
        }
    } else {
        p.v
    }
}

/// The same for a vector curve, per component.
pub fn eval_curve3(keys: &[CurveKeyDef<[f32; 3]>], t: f32, default: Vec3) -> Vec3 {
    if keys.is_empty() {
        return default;
    }
    let mut out = [0.0; 3];
    for (c, o) in out.iter_mut().enumerate() {
        let comp: Vec<CurveKeyDef<f32>> = keys.iter().map(|k| CurveKeyDef { t: k.t, v: k.v[c], a: k.a[c], l: k.l[c], m: k.m }).collect();
        *o = eval_curve(&comp, t, default[c]);
    }
    Vec3::from_array(out)
}

/// The camera actor at time `t` in anim space.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct AnimSample {
    pub location: Vec3,
    pub rotation: Rot,
    pub fov: f32,
    pub interest: Option<Vec3>,
}

impl CameraAnimDef {
    pub fn sample(&self, t: f32) -> AnimSample {
        let location = eval_curve3(self.pos, t, Vec3::ZERO);
        let interest = (!self.interest.is_empty()).then(|| eval_curve3(self.interest, t, Vec3::ZERO));
        let rotation = match interest {
            Some(p) if self.look_at_interest && (p - location).length_squared() > 1e-8 => Rot::looking_along(p - location),
            _ => {
                let e = eval_curve3(self.euler, t, Vec3::ZERO);
                Rot { pitch: e.y, yaw: e.z, roll: e.x }
            }
        };
        AnimSample { location, rotation, fov: eval_curve(self.fov, t, self.base_fov), interest }
    }
}

