/// A view: location (KH world, cm), rotation, FOV (degrees).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct AnimView {
    pub location: Vec3,
    pub rotation: Rot,
    pub fov: f32,
}

impl AnimView {
    /// `FMinimalViewInfo::BlendViewInfo` [U].
    pub fn blend(&self, to: &AnimView, alpha: f32) -> AnimView {
        let d = |a: f32, b: f32| normalize_axis(b - a);
        AnimView {
            location: self.location + (to.location - self.location) * alpha,
            rotation: Rot {
                pitch: self.rotation.pitch + d(self.rotation.pitch, to.rotation.pitch) * alpha,
                yaw: self.rotation.yaw + d(self.rotation.yaw, to.rotation.yaw) * alpha,
                roll: self.rotation.roll + d(self.rotation.roll, to.rotation.roll) * alpha,
            }
            .normalized(),
            fov: self.fov + (to.fov - self.fov) * alpha,
        }
    }
}

/// `ViewTargetTransitionParams` as `SetTresCameraTransitionParams` builds them.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Transition {
    pub time: f32,
    /// `EViewTargetBlendFunction`.
    pub function: u8,
    pub exp: f32,
    pub lock_outgoing: bool,
}

impl Transition {
    pub const CUT: Transition = Transition { time: 0.0, function: 0, exp: 2.0, lock_outgoing: false };

    pub const fn new(time: f32, function: u8, exp: f32, lock_outgoing: bool) -> Transition {
        Transition { time, function, exp, lock_outgoing }
    }

    /// `APlayerCameraManager::UpdateViewTarget`'s blend percentage [U].
    pub fn alpha(&self, elapsed: f32) -> f32 {
        if self.time <= 0.0 {
            return 1.0;
        }
        let x = (elapsed / self.time).clamp(0.0, 1.0);
        match self.function {
            1 => cubic(0.0, 0.0, 1.0, 0.0, x),
            2 => x.powf(self.exp),
            3 => x.powf(1.0 / self.exp),
            4 => {
                if x < 0.5 {
                    0.5 * (2.0 * x).powf(self.exp)
                } else {
                    1.0 - 0.5 * (2.0 * (1.0 - x)).powf(self.exp)
                }
            }
            _ => x,
        }
    }
}

