/// The collision pass after the compose (`FUN_14061CB40`, camera spec 3.3; `EnableCollision(true)`
/// in the three blueprints) [C]: a sphere of the probe radius (`FUN_1405CCFD0`: 20) from the
/// camera's pivot to the composed location; the first blocking hit is the camera's place. The
/// (D4) start point (the 4th argument) is the camera's LOOK POINT: FUN_1405CD6F0 = the camera's
/// location + its view direction x `m_CurrentDistance` (FUN_1405C90A0), which the compose
/// 0x1405DABF0 (CameraAnim) sets just before from vt+0x8F8 (0x1406223B0, the target framing distance)
/// when > 0, else |camera - base 0x70C|; ATresCameraRotTarget 0x14060E790 the same with its pivot.
/// See `sweep_start`; vt+0x8F8's framing (7.8 KB, lock-on / water cases) is not ported: the base
/// distance is used [D].
pub fn sweep_start(view: &AnimView, pivot: Vec3) -> Vec3 {
    view.location + view.rotation.forward() * (view.location - pivot).length()
}

/// (party I1) What `ATresCameraTarget` vt+0x8F8 = 0x1406223B0 (the "outside wall check", camera spec slot
/// 287) hands back to the compose (CameraAnim 0x1405DABF0 / RotTarget 0x14060E790): `distance` > 0 becomes
/// `m_CurrentDistance` (the look point of the collision pass is `location + forward x distance` = `look`), and
/// the camera may have been moved / turned to keep the check point in view.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Framing {
    pub distance: f32,
    pub look: Vec3,
    pub location: Vec3,
    pub rotation: Rot,
}

/// (party I1) `FUN_1406280E0(this, out, a, b, reject_start_penetrating)`: a sphere of the probe radius
/// (FUN_1405CCFD0, 20) swept from `b` to `a` ("Camera_Simple", the target and the ignore lists ignored); the out
/// point is the hit's centre (or `a` with no hit) pulled back toward `b` by this+0x6B0 + 1 (0 + 1, ctor
/// 0x1406161D0). A start-penetrating hit is ignored when asked.
fn wall_probe(world: &dyn kh_core::World, a: Vec3, b: Vec3, reject_start: bool) -> (bool, Vec3) {
    let r = crate::CAMERA_PARAMS.collision_radius;
    let back = (b - a).normalize_or_zero();
    match world.sweep_capsule(b, a, r, r) {
        Some(h) if !(reject_start && h.start_penetrating) => (true, b + (a - b) * h.time.clamp(0.0, 1.0) + back),
        _ => (false, a + back),
    }
}

/// (party I1) `FUN_1405CE070`: the closest points of the line `a0 -> a1` and the line `b0 -> b1` (none when
/// either is degenerate or they are parallel: |1 - (da . db)^2| <= 1e-8).
fn closest_on_lines(a0: Vec3, a1: Vec3, b0: Vec3, b1: Vec3) -> Option<(Vec3, Vec3)> {
    let (da, db) = (a1 - a0, b1 - b0);
    if da.length_squared() <= 0.0 || db.length_squared() <= 0.0 {
        return None;
    }
    let (da, db) = (da.normalize(), db.normalize());
    let c = da.dot(db);
    let den = 1.0 - c * c;
    if den.abs() <= 1e-8 {
        return None;
    }
    let w = b0 - a0;
    let (pa, pb) = (da.dot(w), db.dot(w));
    let ta = (pa - pb * c) / den;
    let tb = (pa * c - pb) / den;
    Some((a0 + da * ta, b0 + db * tb))
}

/// (party I1) `ATresCameraTarget` vt+0x8F8 = 0x1406223B0 (7801 B) for the team cameras, transcribed in world
/// space (an attached camera, vt+0x898 0x140624870, computes the same in its parent's frame; the port's targets
/// turn about Z only, so the parent's up is Z). `check` = the check point of this+0x6B4 (the outside-wall check
/// type: 0 = the base this+0x70C, the type of every team camera but two: Trinity Guard's RotTarget02 type 1 =
/// the target actor's root, the same point here; Goofy's cut05 type 3 "center" plays only against the tower
/// enemies). Steps:
/// 1. W = check + 2.15 z; two probes from W +- r z (r = the probe radius 20) lift / lower the check point out
///    of a floor / ceiling (`wall_probe`, start-penetrating hits ignored; both hit: the upper unless 2 cm farther).
/// 2. The check line P -> P2 = P + 2r z (P - 2r z when the upper probe hits and the lower is clearer by 2 cm).
/// 3. X / Y = the closest points of the view line (camera -> look, look = camera + forward x 20: the compose
///    passes clamp(this+0x464 20, 1, 50)) and the check line; none (parallel) -> no framing (0). K = X when in
///    front of the camera, else the look point.
/// 4. Water (unless the camera config's m_bNoCollision / +0x704 bit 0x10): the "Camera_LookWater" sweep (r + 1)
///    from K + 100 z down to K, else FUN_140626CE0's ocean plane (level + wave + r + 1): K kept above the water
///    surface (`World::water_surface` stands for both [inf: no wave term]); then the look moves to K and the
///    camera keeps its distance to it along the old direction; X / Y again.
/// 5. X behind the camera: the check line becomes P -> P + unit(look - P), X / Y again. A wall on the check
///    line (P2 -> Y) pulls the look back toward the camera; a wall between Y and the look moves the camera to
///    keep its distance and turns it at X (roll kept).
/// 6. The distance = |X - camera| (at least 0.1, the look = X); 1.0 when X lies behind the camera and off the
///    check line (the look unchanged).
pub fn frame_target(view: &AnimView, check: Vec3, world: &dyn kh_core::World) -> Option<Framing> {
    let r = crate::CAMERA_PARAMS.collision_radius;
    let up = Vec3::Z;
    let mut cam = view.location;
    let fwd = view.rotation.forward();
    let mut look = cam + fwd * 20.0_f32.clamp(1.0, 50.0);
    let mut rotation = view.rotation;
    // 1.
    let w = check + up * 2.15;
    let (hit_up, a_out) = wall_probe(world, w, w + up * r, true);
    let (hit_dn, b_out) = wall_probe(world, w, w - up * r, true);
    let p = match (hit_up, hit_dn) {
        (false, false) => check,
        (true, false) => a_out,
        (false, true) => b_out,
        (true, true) => {
            if w.distance(a_out) - 2.0 <= w.distance(b_out) {
                a_out
            } else {
                b_out
            }
        }
    };
    // 2.
    let o = up * (2.0 * r);
    let mut p2 = p + o;
    let (blocked, d_out) = wall_probe(world, p, p2, false);
    if blocked {
        let (hit_e, e_out) = wall_probe(world, p, p - o, false);
        if hit_e && p.distance(e_out) < p.distance(d_out) - 2.0 {
            p2 = p - o;
        }
    }
    // 3.
    let (mut x, mut y) = closest_on_lines(cam, look, p, p2)?;
    if x.distance(look) < 0.01 {
        x = look;
    }
    let k0 = if (x - cam).dot(look - cam) > 0.0 { x } else { look };
    // 4.
    let mut k = k0;
    let watered = match world.water_surface(k + up * 100.0).or_else(|| world.water_surface(k)) {
        // the sweep covers K .. K + 100: a surface farther up starts it inside the water (ignored)
        Some(h) if k.z < h + r + 1.0 && h + r + 1.0 <= k.z + 100.0 => {
            k.z = h + r + 1.0;
            true
        }
        _ => false,
    };
    if watered {
        let back = cam - k0;
        let d = back.length();
        let n = back.normalize_or_zero();
        look = k;
        cam = k + n * d;
        if let Some(q) = closest_on_lines(cam, look, p, p2) {
            (x, y) = q;
        }
    }
    // 5. (uStack_308: the look before the probes below)
    let look_orig = look;
    let mut d2 = (x - cam).length_squared();
    if (look_orig - cam).dot(x - cam) <= 0.0 {
        let p3 = p + (look_orig - p).normalize_or_zero();
        if let Some(q) = closest_on_lines(cam, look, p, p3) {
            (x, y) = q;
        }
        p2 = p3;
        d2 = (x - cam).length_squared();
    }
    let (wall, y_out) = wall_probe(world, y, p2, false);
    if wall {
        let (_, l2) = wall_probe(world, look, cam, false);
        look = l2;
        y = y_out;
        x = look;
        d2 = (x - cam).length_squared();
    }
    let keep = d2.sqrt();
    let (between, l3) = wall_probe(world, look, y, false);
    if between {
        x = l3;
    }
    // 6.
    let v = x - cam;
    let dist = v.length();
    if dist <= 0.0 {
        return Some(Framing { distance: 1.0, look, location: cam, rotation });
    }
    let mut out = 1.0;
    if x.distance_squared(y) < 1.0 || (look_orig - cam).dot(v) >= 0.0 {
        out = dist;
        if between {
            let n = (cam - look_orig).normalize_or_zero();
            cam = l3 + n * keep;
            let to = x - cam;
            out = to.length();
            let r2 = Rot::looking_along(to);
            rotation = Rot { pitch: r2.pitch, yaw: r2.yaw, roll: rotation.roll };
        }
        if out < 0.1 {
            x = cam + (x - cam).normalize_or_zero() * 0.1;
            out = 0.1;
        }
        look = x;
    }
    Some(Framing { distance: out, look, location: cam, rotation })
}

/// The sweep itself (camera spec 3.3): from `pivot` (the look point, `sweep_start`) to `location`.
pub fn collide(pivot: Vec3, location: Vec3, world: &dyn kh_core::World) -> Vec3 {
    let r = crate::CAMERA_PARAMS.collision_radius;
    match world.sweep_capsule(pivot, location, r, r) {
        Some(hit) if !hit.start_penetrating => pivot + (location - pivot) * hit.time.clamp(0.0, 1.0),
        _ => location,
    }
}

fn field_target(at: (Vec3, f32)) -> crate::CameraTarget {
    crate::CameraTarget { position: at.0, yaw: at.1, velocity: Vec3::ZERO, state: crate::TargetState::Idle, collision_half_height: 89.0 }
}

/// One spawned event camera.
#[derive(Clone, Debug, PartialEq)]
struct Cam {
    /// A name for tests and traces (the blueprint's spawn name).
    name: &'static str,
    /// The blueprint that owns it (`EndAllSameBPTresCamera` ends one blueprint's cameras).
    owner: Bp,
    source: Source,
    /// Base yaw (taken once) and the "always" flag of `SetTresCameraTargetInfluenceRotation`.
    base_yaw: Option<f32>,
    yaw_always: bool,
    /// Location influence: X/Y and Z follow every frame (defaults), else the start value.
    xy_always: bool,
    base_xy: Option<(f32, f32)>,
    kind: CamKind,
}

impl Cam {
    fn new(name: &'static str, owner: Bp, source: Source, kind: CamKind) -> Cam {
        Cam { name, owner, source, base_yaw: None, yaw_always: false, xy_always: true, base_xy: None, kind }
    }

    /// The view at the current time (None while its target is missing).
    fn view(&mut self, t: &CameraTargets) -> Option<AnimView> {
        let (mut loc, yaw) = self.source.get(t)?;
        if self.base_yaw.is_none() || self.yaw_always {
            self.base_yaw = Some(yaw);
        }
        if self.base_xy.is_none() || self.xy_always {
            self.base_xy = Some((loc.x, loc.y));
        }
        let (bx, by) = self.base_xy.unwrap_or((loc.x, loc.y));
        loc.x = bx;
        loc.y = by;
        let base_yaw = self.base_yaw.unwrap_or(yaw);
        let rot_yaw = |v: Vec3, a: f32| {
            let (s, c) = a.to_radians().sin_cos();
            Vec3::new(v.x * c - v.y * s, v.x * s + v.y * c, v.z)
        };
        Some(match &self.kind {
            CamKind::Anim { def, time, .. } => {
                let s = def.sample(*time);
                AnimView { location: loc + rot_yaw(s.location, base_yaw), rotation: Rot { pitch: s.rotation.pitch, yaw: s.rotation.yaw + base_yaw, roll: s.rotation.roll }.normalized(), fov: s.fov }
            }
            CamKind::Orbit { distance, rotation, target_offset, local_offset, fov } => {
                let look = loc + rot_yaw(*local_offset, yaw) + *target_offset;
                let r = Rot { pitch: rotation.pitch, yaw: rotation.yaw + base_yaw, roll: rotation.roll }.normalized();
                AnimView { location: look - r.forward() * distance.value(), rotation: r, fov: fov.map_or(t.field.fov, |f| f.value()) }
            }
            CamKind::Field { cam, .. } => {
                let v = cam.as_ref()?.view();
                let view = AnimView { location: v.position, rotation: v.rotation, fov: t.field.fov };
                view
            }
        })
    }

    /// The pivot of the collision pass (the camera's base location).
    fn pivot(&self, t: &CameraTargets) -> Option<Vec3> {
        let (loc, yaw) = self.source.get(t)?;
        Some(match &self.kind {
            CamKind::Orbit { local_offset, target_offset, .. } => {
                let (s, c) = yaw.to_radians().sin_cos();
                loc + Vec3::new(local_offset.x * c - local_offset.y * s, local_offset.x * s + local_offset.y * c, local_offset.z) + *target_offset
            }
            _ => loc,
        })
    }
}

