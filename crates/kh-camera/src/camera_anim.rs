        assert!((eval_curve(&k, 2.5, 0.0) - 8.0).abs() < 1e-5);
        assert_eq!(eval_curve(&k, 2.0, 0.0), 7.0);
        assert_eq!(eval_curve(&k, 5.0, 0.0), 9.0);
