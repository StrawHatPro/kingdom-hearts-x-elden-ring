/// `EInterpCurveMode`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CurveMode {
    Linear,
    CurveAuto,
    Constant,
    CurveUser,
    CurveBreak,
    CurveAutoClamped,
}

/// One `FInterpCurvePoint`: `InVal` (t), `OutVal` (v), arrive / leave tangents (a / l), mode (m).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct CurveKeyDef<T: Copy> {
    pub t: f32,
    pub v: T,
    pub a: T,
    pub l: T,
    pub m: CurveMode,
}

type K<T> = CurveKeyDef<T>;
type M = CurveMode;

