/// A linear move of a value over a time (`SetDistance(d, t)`, `SetFieldOfView(f, t)`) [?: linear].
#[derive(Clone, Copy, Debug, PartialEq)]
struct Ramp {
    from: f32,
    to: f32,
    time: f32,
    elapsed: f32,
}

impl Ramp {
    fn fixed(v: f32) -> Ramp {
        Ramp { from: v, to: v, time: 0.0, elapsed: 0.0 }
    }
    /// `SetDistance` 0x1405EFB60 / `SetFieldOfView` 0x1405D6F40 start the camera's interpolator
    /// with FUN_141194190(type 5, from, to, time) [C]: type 5 of the evaluator 0x1411A0E70 is the
    /// ease-out 1 - (1 - x)^2 (`lockon::interp_curve`); time <= 0 sets the value at once.
    fn value(&self) -> f32 {
        if self.time <= 0.0 {
            self.to
        } else {
            self.from + (self.to - self.from) * crate::lockon::interp_curve(5, self.elapsed / self.time)
        }
    }
    fn set(&mut self, to: f32, time: f32) {
        *self = Ramp { from: self.value(), to, time, elapsed: 0.0 };
    }
    fn step(&mut self, dt: f32) {
        self.elapsed += dt;
    }
}

