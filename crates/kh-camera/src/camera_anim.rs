        // Tangents are per second: scaled by the key interval.
        let s = [CurveKeyDef { t: 0.0, v: 0.0, a: 0.0, l: 2.0, m: CurveMode::CurveUser }, CurveKeyDef { t: 2.0, v: 4.0, a: 2.0, l: 0.0, m: CurveMode::CurveUser }];
