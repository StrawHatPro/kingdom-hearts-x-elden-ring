//! D.4): the CameraAnim player (`ATresCameraAnim`), the orbit camera `ATresCameraRotTarget`, and the
//! three state-event camera blueprints that start them, as data:
//! `BP_TresPlayerStateEvent_donald` (Donald Meteor, Flare Force), `BP_TresPlayerStateEventCamera_
//! goofy_shoot` (Goofy Bombardier), `BP_TresPlayerStateEventCamera_ShieldGuardian` (Trinity Guard).
//! The bytecode readings are in `build/sora_tmp/party/bp_*_cam.txt` (tools/bpdump.js); offsets below
//! (`@1527`) are bytecode offsets of each blueprint's ubergraph.
//!
//! # The CameraAnim (`ATresCameraAnim`) [C]
//!
//! - Start `FUN_1405D9D40`: `UCameraAnimInst::Play(anim, this, rate 1, scale 1, blend 0/0, bLoop, ...,
//!   interest actor, up-vector actor)` (SQEX's extended Play); the transition / end parameters are stored.
//! - Per frame `FUN_1405E0270`: `AdvanceAnim(dt)` moves the camera actor by the anim's tracks; the
//!   actor's relative location / rotation after it ARE the raw keys (the move track's `MoveFrame` is
//!   `IMF_World` and the actor is not attached: `GetMoveRefFrame` = identity [U]); they are copied
//!   (+0x808 location, +0x814 rotation) and the actor is put back. A finished anim with `bAutoEnd`
//!   ends the camera with the end transition (`vt+0x798`); without, it holds its last pose.
//! - Compose `FUN_1405DABF0`: `World = Anim(+0x808, +0x814) * Offset(+0x820, +0x82C) * Base(+0x70C
//!   location, +0x6F8 rotation)`. The base location is the target actor's location every frame
//!   (`m_TargetInfo` actor, `+0x718 & 3`, default 0x2B: X/Y and Z follow); the base rotation is the
//!   target's yaw, taken ONCE at the start (`+0x704` default 9: bit 0 yaw, bit 3 "update once";
//!   `SetTresCameraTargetInfluenceRotation(bAlways = true)` makes it follow every frame). The base
//!   offset is 0 in all three blueprints (`BP_SetTresCameraAnimBaseOffset` is not called).
//! - Rotation: `InterpTrackMove.RotMode` `IMR_LookAtGroup` on the interest group "note"
//!   (`m_CameraInterestInterpGroup`, an SQEX_CameraInterest actor moved by its own track): the camera
//!   looks at the interest point, roll 0 (UE `InterpTrackMove::UpdateTrack` [U]); otherwise the euler
//!   track (x roll, y pitch, z yaw: `FRotator::MakeFromEuler`). FOV: the float track on `FOVAngle` /
//!   `CameraComponent.FieldOfView`, else `BaseFOV`.
//! - NOT PORTED: the camera collision pass after the compose (`FUN_1405C90A0`, `FUN_14061CB40`;
//!   `EnableCollision(true)` in the blueprints): the test level is open ground. [?] which of the
//!   interest and camera groups the anim instance updates first (the look-at here uses the interest
//!   point of the same time; a one-frame lag is possible in the game).
//!
//! # The orbit camera (`ATresCameraRotTarget`, update slot 291 0x14060E790) [C]
//!
//! Look point = target actor location + target rotation x `m_TargetLocalOffset` + `m_TargetOffset`
//! (`FUN_140624260`); rotation = base rotation (target yaw, once or always) + `m_Rotation` (slot 292
//! 0x1405FE430); camera = look point - forward(rotation) x distance. `SetTresCameraRotTargetParam`
//! (0x14060B9C0) writes distance +0x800, rotation +0x828, target offset +0x678, local offset +0x684.
//! [?] `SetDistance(d, t)` / `SetFieldOfView(f, t)` interpolate linearly over `t` here (the curve was
//! not read); the look-point lag (`m_fPositionLerpPer`, `FUN_1405D0B30`) is not applied.
//!
//! # Transitions (`SetTresCameraTransitionParams(BlendTime, BlendFunction, BlendExp, bLockOutgoing, ..)`)
//!
//! Stock UE 4.17 view-target blending [U]: `EViewTargetBlendFunction` 0 linear, 1 cubic, 2 ease in,
//! 3 ease out, 4 ease in-out with the exponent; location and FOV lerp, rotation lerp of the normalized
//! difference; a locked outgoing view is frozen at the switch. Time 0 = a cut.

